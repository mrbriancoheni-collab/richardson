          <h2>What Gets Inspected: A Walk-Through</h2>
          <p><strong>Sprinkler Heads:</strong> Inspectors visually check every head for corrosion, paint, physical damage, or improper orientation. Any painted-over heads must be replaced — paint voids the head's UL listing and prevents proper heat response.</p>
          <p><strong>Control Valves:</strong> All OS&amp;Y (outside stem and yoke) valves, butterfly valves, and post indicator valves are checked to confirm they are fully open and properly sealed or supervised. A closed valve is the leading cause of sprinkler system failure in fires.</p>
          <p><strong>Pipes and Fittings:</strong> Visible pipes are inspected for corrosion, leaks, or physical damage. Hanger and seismic bracing are checked for integrity.</p>
          <p><strong>Alarm Devices:</strong> Water flow switches, tamper switches, and bell gongs are tested to confirm they activate and transmit signals correctly.</p>
          <p><strong>Fire Department Connections (FDC):</strong> The FDC is inspected for caps, clear threads, proper signage, and freedom from obstructions. An obstructed FDC can prevent firefighters from boosting water supply during a fire.</p>
          <p><strong>Internal Pipe Inspection (5-Year):</strong> A contractor opens representative pipe sections to check for internal corrosion, scale, MIC (microbiologically influenced corrosion), or organic growth. This inspection is often skipped by property owners unaware of the requirement — and it's where the most serious system integrity problems are found.</p>

          <h2>Violations and Consequences</h2>
          <p>An NFPA 25 inspection that finds deficiencies results in a written report categorizing each deficiency as:</p>
          <ul>
            <li><strong>Impairment</strong> — system is out of service; must be addressed immediately, fire watch required</li>
            <li><strong>Deficiency</strong> — system is operational but has a problem; must be corrected within 30 days or as required by AHJ</li>
            <li><strong>Recommendation</strong> — best practice; no mandatory timeline</li>
          </ul>
          <p>California AHJs can issue fire code violation notices and, for serious deficiencies, require the property owner to implement a fire watch until the system is restored. For commercial properties, an unresolved impairment can trigger CO or business license issues.</p>

          <h2>How to Select an NFPA 25 Inspector in California</h2>
          <p>Under SB 1205, verify that your inspector holds:</p>
          <ol>
            <li>A current CSLB C-16 Fire Protection Contractor license (verify at <strong>cslb.ca.gov</strong>)</li>
            <li>Active CSFM contractor registration</li>
            <li>NICET certification — indicates specialized training in fire protection testing and maintenance</li>
          </ol>
          <p>Avoid vendors offering NFPA 25 inspections without these credentials — they are operating illegally in California and any inspection report they produce may not be accepted by your AHJ.</p>

