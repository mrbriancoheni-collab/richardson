          <h2>What Is NFPA 25?</h2>
          <p>NFPA 25 is the Standard for the Inspection, Testing, and Maintenance of Water-Based Fire Protection Systems, published by the National Fire Protection Association. It establishes the minimum frequency and procedures for inspecting sprinkler systems, standpipes, fire pumps, water storage tanks, and private fire service mains. In California, NFPA 25 compliance is enforced by the local Authority Having Jurisdiction (AHJ) — typically the local fire department — and since 2019, California SB 1205 requires that inspections be performed by or under the supervision of a contractor holding a CSLB C-16 license and CSFM registration.</p>

          <h2>Why Regular Inspections Matter</h2>
          <p>A fire sprinkler system that hasn't been inspected can fail silently. Heads corrode or get painted over. Valves are left closed after maintenance. Pipes develop obstructions from scale or microbiologically influenced corrosion (MIC). NFPA 25 exists to catch these failure modes before a fire occurs — because a sprinkler that fails to activate means the system provides zero protection.</p>
          <p>According to the National Fire Protection Association, fire sprinkler systems operate as intended in 96% of fires where they activate. The failures are almost always traced to systems that were shut off, not maintained, or obstructed — all conditions that regular NFPA 25 inspections catch.</p>

          <h2>California SB 1205: What Changed in 2019</h2>
          <p>California Senate Bill 1205, effective January 1, 2019, added a critical requirement: all fire protection system inspections, testing, and maintenance in California must be performed by a licensed C-16 fire protection contractor registered with the California State Fire Marshal (CSFM). This closed a gap where unlicensed vendors were performing ITM work. Property owners must now verify their inspection contractor's credentials before signing any service agreement.</p>
          <p>Richardson Fire Protection holds CSLB C-16 License #1053506 and is CSFM registered — meeting every SB 1205 requirement.</p>

