          <h2>What Changed for Warehouse Fire Protection</h2>
          <p>Section 3206 of the 2022 CFC, which governs high-piled combustible storage, received meaningful updates aligned with NFPA 13 2022. The revisions affect several areas relevant to Sacramento Valley distribution and logistics facilities:</p>
          <ul>
            <li><strong>Commodity classification tables:</strong> Updated to align with NFPA 13 2022 commodity classifications, which reorganized Group A, B, and C plastic storage categories and adjusted protection thresholds accordingly.</li>
            <li><strong>In-rack vs. ceiling-only thresholds:</strong> The updated tables revise the conditions under which in-rack sprinklers are required versus ceiling-only ESFR systems, with some configurations that previously qualified for ceiling-only protection now requiring a supplemental in-rack component.</li>
            <li><strong>Group A plastic storage engineering study requirement:</strong> Group A plastic storage over 10 feet in height now explicitly requires an engineered fire protection study in most configurations. This requirement formalizes what many AHJs were already informally requiring for high-challenge storage projects.</li>
          </ul>
          <p>The practical impact for warehouse developers and tenants: commodity classification is now more critical than ever. Misclassifying stored goods at the design phase can result in a system that fails plan check or, worse, requires costly modification after installation.</p>

          <h2>What GCs and Developers Should Do Now</h2>
          <p>Given the code cycle transition and the AHJ adoption variation across the Sacramento Valley, contractors and developers should take the following steps on any new project:</p>
          <ol>
            <li><strong>Confirm which code edition your AHJ has adopted</strong> before starting design. Do not assume — call the fire prevention division directly and ask which CFC edition they are currently enforcing. This single step prevents the most common plan check rejection scenario.</li>
            <li><strong>Check your site's fire hazard severity zone designation</strong> at osfm.fire.ca.gov if your project is in or near WUI-adjacent areas of Placer, Sacramento, El Dorado, or Solano counties. Zone re-designations since 2020 have expanded VHFHSZ boundaries significantly.</li>
            <li><strong>Budget for updated sprinkler requirements</strong> in any Group A occupancy tenant improvement or new construction. The removal of the area exemption for certain Group A subtypes may require sprinklers in spaces that would not have required them under the 2019 CFC.</li>
            <li><strong>Contact Richardson to confirm code cycle</strong> for your specific project jurisdiction. Richardson performs AHJ coordination as part of every project pre-design process, including verifying the current code edition, local amendments, and plan check preferences of the assigned fire prevention plan checker.</li>
          </ol>

