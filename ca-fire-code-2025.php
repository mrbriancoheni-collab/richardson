          <h2>California's Fire Code Adoption Cycle</h2>
          <p>California adopts the International Fire Code (IFC) on a 3-year cycle but amends it extensively to become the California Fire Code (CFC). The 2022 CFC, based on the IFC 2021 edition, took effect January 1, 2023 statewide. However, individual Authorities Having Jurisdiction (AHJs) — typically local fire departments — may adopt the new code on a slightly delayed schedule or apply local amendments that affect how the code is enforced in their jurisdiction.</p>
          <p>Some AHJs in the Sacramento Valley are still enforcing the 2019 CFC for projects that were already in design or permit review before the transition. Always verify which code edition your local fire department is enforcing before beginning plan submittal. Submitting under the wrong code cycle is one of the most common causes of plan check rejection on first pass.</p>

          <h2>Key Changes in the 2022 CFC for Fire Sprinklers</h2>
          <p>The 2022 California Fire Code made several significant changes to fire sprinkler requirements under Section 903:</p>
          <ul>
            <li><strong>Group A occupancies:</strong> The 2022 CFC now requires fire sprinklers in all new Group A occupancies (assembly uses including theaters, restaurants, and places of worship) regardless of floor area. The previous 2019 CFC included a 5,000 sq ft threshold exemption for certain Group A subtypes — that exemption is removed in the 2022 edition.</li>
            <li><strong>Outdoor storage areas:</strong> New sprinkler requirements now apply to outdoor storage areas exceeding 20,000 sq ft when the storage involves combustible materials.</li>
            <li><strong>NFPA 13 2022 edition:</strong> The 2022 CFC references the NFPA 13 2022 edition as the installation standard, which includes updated K-factor requirements for high-challenge storage occupancies and revised water demand calculations for certain rack storage configurations.</li>
            <li><strong>Group B (office) occupancies:</strong> The sprinkler threshold for Group B office buildings remains at 5,000 sq ft in most occupancy configurations, consistent with the 2019 CFC.</li>
          </ul>

          <h2>WUI Zone Expansion and Fire Protection</h2>
          <p>One of the most regionally significant changes in the 2022 CFC is the expansion of State Responsibility Area (SRA) fire hazard severity zone mapping. Following CAL FIRE's post-2017 wildfire reassessments, the updated mapping substantially expanded the footprint of Very High Fire Hazard Severity Zone (VHFHSZ) designations across Northern California.</p>
          <p>The 2022 CFC's CalFire Chapter 12 now applies to more properties in the Sacramento Valley region, including areas of Placer County (Rocklin foothills, Lincoln), Sacramento County (Orangevale, Rancho Murieta), and Solano County (Vacaville/Fairfield interface zones). Properties newly designated as VHFHSZ face additional construction requirements under California Building Code Chapter 7A, which includes fire-resistant roofing, ember-resistant vents, and in many cases fire sprinkler systems for residential construction.</p>
          <p>If your project is in or near these zones and you have not checked your current fire hazard severity zone designation, do so before beginning design. Zone changes since 2020 have caught many developers by surprise during plan check.</p>

