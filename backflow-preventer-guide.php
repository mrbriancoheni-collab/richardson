          <h2>Backflow Preventer Location and Maintenance Requirements</h2>
          <p>Proper installation and ongoing maintenance of the backflow preventer affects both testing access and device longevity:</p>
          <ul>
            <li><strong>Installation height:</strong> RPZ assemblies must be installed with the relief valve outlet oriented to discharge to a drain. Most water districts require installation height between 12 and 36 inches above the floor to allow test equipment access and prevent debris from blocking the relief valve drain.</li>
            <li><strong>Minimum clearances:</strong> ASSE 1013 (the product standard for RPZ assemblies) and local water district standards require minimum clearances around the assembly for testing access — typically 12 inches on the side and 12 inches above the relief valve. Installations crammed against walls or in confined spaces make testing difficult and are a common code compliance issue in older buildings.</li>
            <li><strong>Freeze protection:</strong> RPZ assemblies installed outdoors or in unheated spaces must be protected from freezing. Frozen RPZ bodies crack — a catastrophic failure mode that floods the surrounding area and requires immediate replacement. Heat tape, insulation enclosures, or indoor relocation are acceptable solutions depending on the installation.</li>
            <li><strong>Outdoor enclosures:</strong> Backflow preventers installed in outdoor above-ground enclosures must meet water district specifications for enclosure type, ventilation, and lock. Some districts prohibit certain enclosure types in high-traffic areas. Richardson specifies and installs code-compliant enclosures for all outdoor installations.</li>
            <li><strong>Downstream shutoff:</strong> A listed shutoff valve downstream of the backflow preventer is required for isolation during testing and repair. If this valve is missing or seized, it must be repaired before the annual test can be performed.</li>
          </ul>

