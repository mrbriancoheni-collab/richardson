          <h2>Why Every Fire Sprinkler System Has a Backflow Preventer</h2>
          <p>California Health and Safety Code Section 116800 and local water district cross-connection control programs require a physical barrier between any fire protection system and the public potable water supply. This requirement exists because fire sprinkler systems are classified as a high-hazard cross-connection — meaning contamination from the sprinkler system could seriously threaten public health.</p>
          <p>The concern is real. Inside a fire sprinkler system, stagnant water sits for months or years, accumulating corrosion products, bacteria (including Legionella in some configurations), nitrogen (in supervised dry systems), and in older systems, anti-freeze compounds (some of which are toxic). Without a backflow preventer, any pressure drop on the municipal supply side — caused by a main break, firefighting operations nearby, or a large demand event — could cause this contaminated water to siphon backward into the potable water distribution system.</p>
          <p>California requires a backflow preventer on every fire protection service connection. The specific device type required depends on the local water district's cross-connection control program — most Sacramento Valley districts require the highest level of protection for fire system connections.</p>

          <h2>Types of Backflow Prevention Devices Used in Fire Systems</h2>
          <p>Two device types are most commonly specified for fire protection service connections in California:</p>
          <p><strong>Reduced Pressure Zone (RPZ) Backflow Preventer:</strong> This is the gold standard for fire protection connections in Sacramento Valley. An RPZ assembly has two independently operating check valves separated by a reduced-pressure zone, plus a hydraulically operated differential pressure relief valve that opens to the atmosphere if either check valve fails. The result: if the RPZ fails, it discharges water to a drain rather than allowing contamination to pass. Most Sacramento-area water districts — Sacramento Suburban Water District, Cal Water, Roseville Utilities — require an RPZ on all fire protection service connections.</p>
          <p><strong>Double Check Valve Assembly (DCVA):</strong> A DCVA has two independently operating check valves in series but no relief valve. It is approved for lower-hazard connections in some districts. Some water districts permit a DCVA for limited-use residential fire systems (NFPA 13D) but require an RPZ for commercial fire systems. Verify with your local water district before specifying a DCVA — using an under-specified device is a code violation that will require replacement at the owner's expense.</p>
          <p>Richardson designs and installs backflow preventers to water district specifications for every new fire protection service connection. We also coordinate the initial test with a certified tester and submit results to the district's backflow program.</p>

          <h2>Annual Testing Requirements</h2>
          <p>Backflow preventers on fire protection connections must be tested annually. This requirement comes from multiple overlapping regulatory authorities:</p>
          <ul>
            <li><strong>California Health and Safety Code:</strong> Requires annual testing of all backflow prevention assemblies on commercial service connections.</li>
            <li><strong>Local water district:</strong> Each district has a cross-connection control program that sets testing requirements and requires results be submitted directly to the district's backflow program database. Failure to submit results on time can trigger a notice of violation and, eventually, service interruption.</li>
            <li><strong>NFPA 25:</strong> Requires annual inspection of the backflow preventer as part of the fire protection system ITM program. The NFPA 25 inspection record and the water district test record are separate documents — both must be maintained.</li>
          </ul>
          <p><strong>What the annual test involves:</strong> A certified cross-connection control specialist (CCCS) uses a differential pressure test kit to measure the pressure differential across each check valve and verify that the relief valve on an RPZ opens at the correct differential. The test takes 30–60 minutes for a standard commercial RPZ. A test report is generated on site and submitted to the water district's backflow program database within the timeframe specified by the district (typically 10–30 days after the test date).</p>
          <p>Richardson holds certified cross-connection control specialist credentials and can test, document, and submit backflow preventer test reports to all Sacramento Valley water district programs as part of an annual ITM contract.</p>

          <h2>What Happens If the Backflow Preventer Fails Its Test</h2>
          <p>A failed test must be reported to the water district and corrected before the next scheduled use of the fire system. Depending on the nature of the failure:</p>
          <ul>
            <li><strong>Check valve failure:</strong> If one or both check valves test below the minimum differential pressure (typically 1.0 psi for the second check on an RPZ), the check valve seat or disc must be repaired or replaced. This is a repair-in-place procedure in most cases, costing $200–$600.</li>
            <li><strong>Relief valve fouled or stuck:</strong> RPZ relief valves that have been discharging (you'll see water staining or dripping near the relief valve port) indicate that the first check valve is leaking. This is an immediate repair requirement — continuous discharge through the relief valve means the first line of protection has failed.</li>
            <li><strong>Corrosion or physical damage:</strong> Severe internal corrosion, cracked body, or external damage from freezing may require full replacement rather than repair.</li>
          </ul>
          <p><strong>Service interruption risk:</strong> Water districts can and do issue service shut-off notices for backflow preventers that have failed tests and have not been repaired within the required timeframe. For a commercial building, a water service shut-off means the fire sprinkler system is impaired — triggering fire watch requirements and notification to the AHJ under NFPA 25 Section 15.5.</p>
          <p>Richardson responds to backflow preventer repair requests within 24 hours for commercial clients under ITM contracts.</p>

