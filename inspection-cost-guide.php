          <h2>The 5-Year Internal Inspection: What It Costs and Why It's Required</h2>
          <p>NFPA 25 Chapter 14 requires an obstruction investigation on all wet-pipe and dry-pipe fire sprinkler systems every 5 years. This is the most frequently skipped inspection requirement in California — and the one with the most serious consequences when ignored.</p>
          <p>The 5-year inspection involves opening representative pipe ends and inspecting the interior of the piping for:</p>
          <ul>
            <li><strong>MIC (microbiologically influenced corrosion):</strong> Bacterial colonies that form biofilm inside pipe walls, causing accelerated corrosion that can perforate pipe within 5–10 years in susceptible systems. MIC is endemic in Northern California water supplies and extremely common in systems that have never been treated.</li>
            <li><strong>Scale and mineral deposits:</strong> Hard water deposits can partially or fully obstruct sprinkler orifices, reducing flow below design demand.</li>
            <li><strong>Organic growth:</strong> Found in systems with stagnant water, particularly in infrequently used zones.</li>
            <li><strong>Foreign debris:</strong> Construction debris, pipe shavings, or rodent nesting material from the original installation.</li>
          </ul>
          <p>Cost for a 5-year internal inspection ranges from $800 to $2,500 depending on building size, number of zones, and access conditions. If obstruction is found, an obstruction investigation under NFPA 25 Chapter 14 is required, costing $1,200 to $3,500 for the full flush-and-document procedure.</p>
          <p>Many low-cost inspection contractors skip this requirement or don't disclose it to building owners. If your inspection provider has never mentioned the 5-year internal inspection, ask them directly whether they perform it — and whether their quote includes it.</p>

          <h2>How to Compare Fire Sprinkler Inspection Quotes</h2>
          <p>When evaluating competing inspection quotes, ask each contractor the following questions before signing:</p>
          <ol>
            <li><strong>Does your quote include a written NFPA 25 inspection report?</strong> Some vendors provide verbal-only reports or a one-page sign-off sheet. This does not meet NFPA 25 requirements and will not satisfy your AHJ if a deficiency is later discovered.</li>
            <li><strong>Does the quote include SB 1205 certification submitted to CSFM?</strong> This is a legal requirement in California. If the contractor doesn't know what SB 1205 is, do not use them.</li>
            <li><strong>Does the quote include AHJ notification before waterflow testing?</strong> Most AHJs require advance notice before annual tests. Missing this step can result in false alarm fees and strained relationships with the fire department.</li>
            <li><strong>Are deficiencies documented with photos?</strong> Written deficiency documentation is required by NFPA 25 and is essential for insurance and AHJ compliance purposes.</li>
            <li><strong>Can you provide your CSLB C-16 license number and CSFM registration number?</strong> Verify both at cslb.ca.gov and osfm.fire.ca.gov before signing any contract.</li>
          </ol>
          <p><strong>Red flags:</strong> Significantly below-market quotes (more than 40% below the ranges above), no mention of a written report, verbal credentials only, or reluctance to provide license numbers. Unlicensed inspection is illegal in California under SB 1205 and invalidates your compliance documentation.</p>
