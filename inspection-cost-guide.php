          <h2>What Is Included in a Standard Annual NFPA 25 Inspection</h2>
          <p>A fully compliant annual NFPA 25 inspection includes the following procedures — confirm that your inspector's quote covers all of them:</p>
          <ul>
            <li><strong>Visual inspection of all sprinkler heads</strong> — corrosion, paint, physical damage, improper orientation, missing escutcheons</li>
            <li><strong>Pipe and fitting inspection</strong> — corrosion, leaks, damaged hangers, seismic bracing integrity</li>
            <li><strong>Control valve inspection and position verification</strong> — all OS&amp;Y, butterfly, and post indicator valves confirmed fully open and properly sealed or electrically supervised</li>
            <li><strong>Gauge inspection</strong> — pressure gauges checked for calibration or damage</li>
            <li><strong>Alarm device test</strong> — waterflow switches, tamper switches, and alarm bell or horn/strobe tested for activation and signal transmission</li>
            <li><strong>Fire department connection (FDC) inspection</strong> — caps present, threads clean and undamaged, signage correct, no obstructions within 36 inches</li>
            <li><strong>Written NFPA 25 inspection report</strong> — with itemized deficiency documentation, photos of deficiencies, and corrective action priority list</li>
            <li><strong>SB 1205 certification</strong> — submitted directly to the CSFM certification database (required for all California commercial and multifamily properties since 2019)</li>
          </ul>
          <p>Any quote that does not include a written report and SB 1205 certification is not a complete NFPA 25 inspection under California law.</p>

