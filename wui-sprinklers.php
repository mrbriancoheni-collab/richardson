          <h2>What Is a WUI Zone and Why It Matters</h2>
          <p>"WUI" (Wildland-Urban Interface) refers to areas where developed land meets or intermingles with undeveloped wildland. California CAL FIRE designates lands across the state into two primary responsibility categories: State Responsibility Areas (SRA), where CAL FIRE has primary firefighting responsibility, and Local Responsibility Areas (LRA), which include incorporated cities and most suburban areas where local fire departments have jurisdiction.</p>
          <p>Within SRA lands, CAL FIRE enforces its own fire safe regulations under Title 14 CCR, which govern construction standards, vegetation management, and fire protection requirements. In LRA areas, local fire departments and building departments have jurisdiction, but properties within high or very high fire hazard severity zones in LRA are still subject to additional construction requirements under the California Building Code. Both categories can trigger significantly elevated fire protection requirements that affect your project's budget and design.</p>

          <h2>How to Look Up Your Property's Fire Hazard Severity Zone</h2>
          <p>The California Office of the State Fire Marshal maintains official fire hazard severity zone maps for both SRA and LRA lands. Visit <strong>osfm.fire.ca.gov/informationsharing/fhsz-maps/</strong> to look up any parcel by county. The zones are:</p>
          <ul>
            <li><strong>Moderate Fire Hazard Severity Zone:</strong> Elevated fire risk; additional requirements are limited in most LRA areas but apply fully in SRA</li>
            <li><strong>High Fire Hazard Severity Zone:</strong> Significant risk; triggers defensible space requirements and in some jurisdictions, sprinkler or construction requirements</li>
            <li><strong>Very High Fire Hazard Severity Zone (VHFHSZ):</strong> Maximum designation; triggers mandatory CBC Chapter 7A fire-resistive construction requirements for all new construction and substantial remodels</li>
          </ul>
          <p>New construction in a VHFHSZ must comply with California Building Code Chapter 7A (fire-resistant construction materials and methods) and California Residential Code Chapter R327 for residential projects. These chapters govern roofing, siding, eaves, vents, decking, windows, and fire sprinkler systems.</p>

          <h2>CalFire Chapter 12: WUI Construction Requirements</h2>
          <p>California Fire Code CalFire Chapter 12 establishes fire protection requirements for new construction in fire hazard severity zones. Key requirements include:</p>
          <ul>
            <li><strong>Fire-resistant roofing:</strong> Class A roofing assembly required for all new construction in High and Very High FHSZ</li>
            <li><strong>Ember-resistant vents:</strong> Attic, crawl space, and foundation vents must be ember-resistant (1/16" mesh or tested assemblies)</li>
            <li><strong>Non-combustible eaves:</strong> Exposed rafter tails and eave soffits must be non-combustible or ignition-resistant</li>
            <li><strong>Fire sprinkler systems:</strong> In SRA lands, NFPA 13D fire sprinklers are required in all new single-family and two-family dwellings. This requirement applies throughout SRA regardless of specific FHSZ designation within SRA.</li>
          </ul>
          <p>For multi-story multifamily projects in WUI zones, the applicable standard depends on building height and occupancy: NFPA 13R for buildings up to 4 stories in height, NFPA 13 for buildings 5 stories or greater, consistent with the statewide CBC requirements that also apply.</p>

          <h2>AB 38: Home Sales and Fire Hardening</h2>
          <p>Assembly Bill 38, effective January 1, 2021, added disclosure requirements for home sales in high and very high fire hazard severity zones. Sellers must provide buyers with documentation confirming compliance with local vegetation management (defensible space) ordinances. If the seller cannot confirm compliance, they must disclose this fact to the buyer and provide information on how to achieve compliance.</p>
          <p>Related legislation, including AB 3074, has strengthened defensible space inspection requirements in certain counties. The practical impact for property owners and developers in WUI-adjacent areas: fire hardening features and defensible space compliance are now material to real estate transactions, not just permitting, increasing the importance of code-compliant fire protection systems as a property value and marketability factor.</p>

