          <p>The Sacramento Valley and adjacent foothill areas contain significant WUI-zone coverage across multiple counties. Richardson has worked in all of the following areas:</p>
          <ul>
            <li><strong>Placer County:</strong> Lincoln (eastern areas), Rocklin foothills, Loomis, Penryn, Newcastle, Colfax — substantial SRA and VHFHSZ coverage in the foothill and Sierra Nevada foothills belt</li>
            <li><strong>Sacramento County:</strong> Orangevale, Fair Oaks hillside areas, Rancho Murieta, Sloughhouse — LRA with VHFHSZ designations that trigger Chapter 7A requirements</li>
            <li><strong>El Dorado County:</strong> El Dorado Hills (portions), Cameron Park (some areas) — mixed LRA/SRA with significant WUI development activity</li>
            <li><strong>Solano County:</strong> Vacaville and Fairfield foothill interface areas — expanded VHFHSZ coverage following post-2017 CAL FIRE reassessments</li>
          </ul>
          <p>Zone boundaries shift following major fire events and CAL FIRE reassessments, so checking the current official map is essential even if you are familiar with the general area.</p>

          <h2>What NFPA 13D Costs in a WUI Zone</h2>
          <p>An NFPA 13D fire sprinkler system for a typical single-family home in the Sacramento Valley typically runs $6,500–$14,000 installed. The wide range reflects differences in number of sprinkler heads, layout complexity, water supply configuration, and local AHJ requirements for concealed-space coverage.</p>
          <p>WUI-compliant systems may add $1,000–$3,000 to standard pricing for several reasons: attic coverage requirements (some WUI AHJs require heads in attic spaces that NFPA 13D would otherwise permit to be unprotected), CalFire inspection coordination for SRA projects, and site-specific water supply challenges common in foothill and rural locations where municipal water pressure and flow may be limited. Richardson assesses water supply during pre-design and identifies any pressure-boosting or storage tank requirements before the design is finalized.</p>

