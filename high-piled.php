          <h2>What Is High-Piled Storage?</h2>
          <p>Under the California Fire Code (CFC) Section 3202 and NFPA 13, "high-piled storage" refers to solid-piled, palletized, rack storage, bin box storage, or shelf storage in excess of 12 feet in height. When your warehouse stores materials above 12 feet, you trigger a separate fire protection regulatory category with specific sprinkler system, aisle, and permit requirements.</p>
          <p>High-piled storage is one of the most technical and frequently misunderstood areas of fire protection. Getting the design wrong — or skipping the fire protection upgrade when storage heights change — can result in failed inspections, inventory loss in a fire, and significant liability exposure.</p>

          <h2>When Does High-Piled Storage Trigger a Permit?</h2>
          <p>A high-piled storage permit is required under CFC Chapter 32 when:</p>
          <ul>
            <li>Solid-piled storage exceeds 12 feet in height in a building with a fire area over 500 sq ft</li>
            <li>Rack storage exceeds 12 feet in any configuration</li>
            <li>You store Group A plastics (the most hazardous commodity) above 6 feet</li>
            <li>The building is used for high-piled storage of any commodity over 2,500 sq ft in floor area</li>
          </ul>
          <p><strong>Important:</strong> Moving inventory — even without construction — can trigger a permit requirement. If a tenant changes their storage commodity or increases storage height, the fire protection system may need to be re-evaluated. Richardson recommends a fire protection review whenever storage configurations change significantly.</p>

