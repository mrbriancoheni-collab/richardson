          <h2>Overview: Who Issues Fire Sprinkler Permits in Sacramento</h2>
          <p>Fire sprinkler permits in Sacramento City are issued by the Sacramento City Fire Department (SCFD) Prevention Division, located at Fire Station 1 on H Street. The SCFD handles all fire life safety permits for projects within the Sacramento city limits — which covers most of the central city, Midtown, Land Park, South Natomas, and the airport area, among others.</p>
          <p>Jurisdiction boundaries matter: unincorporated Sacramento County falls under Sacramento County Fire (a separate department), while incorporated cities within the county — Elk Grove, Rancho Cordova, and Citrus Heights — each maintain their own fire departments with independent permit processes, fee schedules, and plan check timelines. Richardson navigates all of these departments and knows the specific requirements and preferences of each plan checker.</p>

          <h2>The 8-Step Permit Process</h2>
          <ol>
            <li><strong>Scope Definition &amp; AHJ Pre-Application:</strong> Before design begins, confirm the occupancy classification, whether the project meets the sprinkler threshold under the current CFC edition the SCFD is enforcing, and whether any local amendments apply. Richardson performs this AHJ coordination as standard pre-design practice.</li>
            <li><strong>Hydraulic Calculations &amp; Design Drawings:</strong> Richardson's NICET-certified designers produce hydraulic flow calculations, pipe schedule, and head layout drawings prepared to NFPA 13, NFPA 13R, or NFPA 13D standards as applicable to the project. All calculations are stamped by a NICET Level III or IV technician.</li>
            <li><strong>Permit Application via Accela:</strong> SCFD uses the Accela online portal for all fire sprinkler permit applications. The application requires contractor license information (C-16 license number and CSLB registration), project valuation, owner information, and site address. Richardson prepares and submits all Accela applications in our company name.</li>
            <li><strong>Digital Plan Submittal:</strong> SCFD accepts digital plan submittals through the Accela portal. Richardson uploads stamped drawings and the complete hydraulic calculation package in SCFD's required format, including cover sheet, site plan, floor plan with head layout, riser diagram, and calculation basis of design.</li>
            <li><strong>Plan Check Assignment:</strong> After submittal, SCFD assigns the project to a fire prevention plan checker, typically within 3–5 business days of a complete application being received. The assigned plan checker's name is visible in Accela, which allows Richardson to follow up directly if questions arise.</li>
            <li><strong>Plan Check Period:</strong> Commercial fire sprinkler plan check at SCFD typically takes 4–8 weeks from the date of a complete submittal. Projects with complex hydraulics, unusual occupancies, or incomplete submittals may take longer. SCFD issues corrections as a written correction list through Accela.</li>
            <li><strong>Correction Response:</strong> When corrections are issued, Richardson revises the plans and hydraulic calculations to address each item and resubmits through Accela. Richardson's goal on every project is first-pass approval — a complete, SCFD-formatted submittal package is the most reliable way to avoid a second correction cycle, which can add 2–4 weeks to the schedule.</li>
            <li><strong>Permit Issuance &amp; Inspection Scheduling:</strong> Once SCFD approves the plans, the permit is issued through Accela and is available for download. Inspection milestones for fire sprinkler installations are: rough-in inspection, above-ceiling inspection (before ceiling cover), hydrostatic pressure test, and final inspection. Richardson schedules all inspections and manages the inspection process through final sign-off.</li>
          </ol>

          <h2>SCFD-Specific Tips from Richardson's Experience</h2>
          <p>Richardson has submitted hundreds of fire sprinkler permit packages to SCFD. Here's what we've learned about avoiding corrections and keeping projects on schedule:</p>
          <ul>
            <li><strong>Complete submittals are the single best investment:</strong> A plan package missing any required element — waterflow test data, basis of design, seismic bracing schedule — will be rejected as incomplete before it even reaches plan check. Richardson uses an internal SCFD checklist before every submittal.</li>
            <li><strong>Common SCFD correction topics:</strong> Missing or outdated waterflow test data (the city water utility test must be within 12 months), non-compliant head spacing in corridors or closets, missing seismic bracing notes and calculations, and improperly sized pipe on hydraulically calculated systems. Richardson's designers know these pain points and address them before submittal.</li>
            <li><strong>Online tracking:</strong> Digital submittal through Accela means you can check the status of your permit application online without calling the department. Richardson provides clients with their Accela permit application number at submittal so they can monitor progress directly.</li>
            <li><strong>Expedited review:</strong> SCFD offers an expedited plan review for an additional fee. Availability varies by current workload. Richardson recommends checking expedite availability when a project schedule is tight — it can reduce review time by 2–4 weeks on qualifying projects.</li>
