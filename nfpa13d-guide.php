              <button class="faq-question" aria-expanded="false">
                Can NFPA 13D be used for a small apartment building or townhouse complex?
                <i class="fa-solid fa-chevron-down"></i>
              </button>
              <div class="faq-answer">
                <p>NFPA 13D applies specifically to one- and two-family dwellings and manufactured homes — not apartment buildings. Townhouses (attached single-family units separated by fire walls from foundation to roof) qualify for NFPA 13D. Attached units that share a floor/ceiling assembly (stack flats, stacked condos) are classified as apartment buildings and require NFPA 13R or NFPA 13 depending on the number of stories.</p>
