              </button>
              <div class="faq-answer">
                <p>NFPA 13D requires a hydrostatic pressure test of the system piping at 200 psi (or 50 psi above the maximum operating pressure, whichever is greater) for 2 hours before concealment. Richardson conducts this test after rough-in and before drywall, with the AHJ inspector present for verification. After the test, the system is visually inspected for proper coverage and head placement before the final inspection at certificate of occupancy.</p>
