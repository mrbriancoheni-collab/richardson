            <div class="faq-item">
              <button class="faq-question" aria-expanded="false">
                What happens if the homeowner's remodel removes or paints over sprinkler heads?
                <i class="fa-solid fa-chevron-down"></i>
              </button>
              <div class="faq-answer">
                <p>Painted sprinkler heads are a code violation — paint fills the glass bulb solder point or covers the deflector, preventing proper activation. NFPA 25 requires painted heads to be replaced. For residential owners doing their own remodeling, Richardson recommends covering heads with the manufacturer's provided protective cap during painting, then removing the cap when painting is complete. If a head is accidentally painted, it must be replaced by a C-16 licensed contractor.</p>
              </div>
            </div>

