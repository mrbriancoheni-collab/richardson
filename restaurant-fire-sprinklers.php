          <h2>Which NFPA 13 Hazard Classification Applies to Restaurants?</h2>
          <p>Hazard classification is the foundation of a sprinkler system design — it determines the design density (gallons per minute per square foot) and the hydraulic calculation area, which together determine pipe sizing, head spacing, and water supply demand. Getting the classification wrong means submitting a design the AHJ will reject, or worse, installing an undersized system that fails in a fire.</p>
          <p>California AHJs typically classify restaurant occupancies as follows: dining rooms, bars, and front-of-house areas are Light Hazard (design density 0.10 gpm/sq ft over 1,500 sq ft). Commercial kitchens with standard cooking equipment are Ordinary Hazard Group 1 (0.15 gpm/sq ft over 1,500 sq ft). Commercial kitchens with heavy cooking loads, fryers, or multiple cooking stations may be classified as Ordinary Hazard Group 2 (0.20 gpm/sq ft over 1,500 sq ft). The difference in water demand between Light Hazard and OH Group 2 is substantial — it can affect pipe sizing, fire pump requirements, and the available water supply adequacy for the entire project.</p>
          <p>Richardson always confirms occupancy classification with the AHJ before finalizing shop drawings for restaurant projects. Local fire prevention staff in Sacramento have specific preferences that may differ from the minimum NFPA 13 guidance, and an informal pre-submittal meeting on a restaurant TI saves correction cycles.</p>

          <h2>Sprinklers and Type I Commercial Kitchen Hoods</h2>
          <p>One of the most common misconceptions on restaurant TIs is the relationship between fire sprinklers and commercial kitchen hood suppression systems. NFPA 13 does <em>not</em> require fire sprinklers inside or directly below a Type I exhaust hood — the hood has its own listed fire suppression system (typically a wet chemical UL 300 system) that is specifically listed for grease fires. Sprinkler heads should not be placed where they will be within the activation cone of the hood suppression system nozzles, because accidental sprinkler discharge and simultaneous hood suppression can interfere with each other.</p>
          <p>The critical coordination issue is spatial: the hood suppression contractor and the fire sprinkler contractor must coordinate head placement relative to the hood perimeter and the suppression nozzle pattern. Richardson's standard practice on restaurant projects is to request the hood shop drawings before finalizing the sprinkler layout, confirming that our heads are outside the suppression system's zone of influence. This coordination step is often overlooked on fast-track TIs, resulting in field conflicts during installation.</p>

          <h2>When Does a Restaurant TI Require Sprinklers?</h2>
          <p>California requires fire sprinkler systems in all new Group A-2 occupancies (restaurants, bars, nightclubs, banquet halls) with an occupant load of 50 or more, or a floor area exceeding 300 square feet, per CBC Section 903.2.1.2. This threshold is lower than many GCs expect — a 300 sq ft café space triggers the full sprinkler requirement under California law.</p>
          <p>Change of occupancy is the most common trigger on restaurant TIs. Converting a retail shell (Group M) or office space (Group B) to restaurant (Group A-2) triggers the sprinkler requirement regardless of whether the existing building was sprinklered. If the existing building has no sprinklers, the entire building may need a sprinkler system installed — a scope that can run $2–$4 per sq ft on the total building area, not just the restaurant space.</p>
          <p>For TIs within existing sprinklered buildings, the change of occupancy requires a hazard reclassification review. If the existing system was designed for Light Hazard and the new restaurant kitchen is Ordinary Hazard Group 1 or 2, the hydraulic calculations for the affected area must be revised and the system modified to meet the higher demand. This is not a minor head relocation — it may require re-piping the kitchen zone.</p>

          <h2>High-Temperature Sprinkler Heads in Commercial Kitchens</h2>
          <p>Standard-response and quick-response sprinkler heads are rated for ordinary temperatures (135–170°F activation). Above commercial cooking equipment — fryers, griddles, ranges, ovens — the ambient temperature regularly exceeds the activation threshold of a standard head. NFPA 13 Section 8.3 prohibits the use of standard or intermediate temperature heads in locations where ceiling temperatures routinely exceed 100°F, and requires high-temperature rated heads (activation at 212–300°F) in kitchen cooking areas.</p>
          <p>The result is that a restaurant kitchen requires two head types in the same space: standard or intermediate heads away from the cooking equipment, and high-temperature heads directly above cooking surfaces and exhaust hoods. The layout must clearly delineate these zones on the shop drawings, and the contractor must install the correct head type in each location. Using a standard head above a fryer is a code violation that will be caught on final inspection and requires head replacement.</p>
          <p>When the cooking equipment layout changes after sprinkler permit submittal — which is common on restaurant TIs as operators make last-minute equipment decisions — the sprinkler layout must be updated to reflect the new cooking equipment positions. Richardson builds kitchen equipment coordination into every restaurant scope and requests a final equipment plan before trimming out the system.</p>

          <h2>The Restaurant TI Permit Process in Sacramento</h2>
          <p>Restaurant fire sprinkler TI permits in Sacramento follow the same SCFD Accela submittal process as commercial TIs, with additional documentation requirements. Required submittal documents include: architectural plan showing occupancy classifications and equipment layout, reflected ceiling plan showing ceiling heights and head locations, sprinkler shop drawings with complete hydraulic calculations, hood suppression coordination letter confirming sprinkler-to-hood coordination, and (for change of occupancy) a code analysis showing compliance with CBC Section 903.2.1.2.</p>
          <p>Typical review time for a restaurant TI fire sprinkler permit in Sacramento is 4–8 weeks. SCFD Fire Prevention reviewers are accustomed to restaurant submissions and will catch kitchen hazard classification issues and head temperature rating errors if they appear in the submittal. Richardson's first-pass submittal rate on restaurant projects exceeds 85% — meaning most of our restaurant TI permits are approved without correction cycles.</p>

